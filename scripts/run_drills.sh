#!/usr/bin/env bash
# run_drills.sh - guided failure drills: reproduce and resolve 15 failures, then exercise the Bash diagnostics.
#
# Run from the integrx folder with the stack up (docker compose up -d):
#   bash scripts/run_drills.sh
#
# For every failure it: reproduces it -> checks the failure code -> shows the diagnosis ->
# applies the runbook fix -> resends or replays -> verifies PROCESSED -> drafts the customer reply ->
# YOU approve it (human approval) -> sends it -> resolves the incident -> records evidence.
set -u

REPO="$(cd "$(dirname "$0")/.." && pwd)"
cd "$REPO" || exit 1
# Activate a virtual environment if one is given or found next to the workspace.
VENV="${VENV:-$REPO/../../.venv}"
# shellcheck disable=SC1091
[[ -f "$VENV/bin/activate" ]] && . "$VENV/bin/activate"
command -v pdoc >/dev/null || { echo "pdoc not found: pip install -e ../payload-doctor (inside your venv)"; exit 1; }
export INTEGRX_ADMIN_KEY="${INTEGRX_ADMIN_KEY:-change-me-admin-key}"
API="http://localhost:8080"
KEY="$INTEGRX_ADMIN_KEY"
PD="../payload-doctor/samples"
EVID="evidence/failure-drills.md"
mkdir -p evidence

B=$'\e[1m'; G=$'\e[32m'; R=$'\e[31m'; Y=$'\e[33m'; C=$'\e[36m'; N=$'\e[0m'
say()   { echo; echo "${B}${C}== $*${N}"; }
ok()    { echo "${G}✔ $*${N}"; }
warn()  { echo "${Y}! $*${N}"; }
bad()   { echo "${R}✘ $*${N}"; }
pause() { read -r -p "${B}Press Enter to continue...${N}" _; }

api()   { curl -s -H "X-Admin-Key: $KEY" "$API$1"; }
post()  { curl -s -X POST -H "X-Admin-Key: $KEY" -H 'Content-Type: application/json' "$API$1" ${2:+-d "$2"}; }
txn()   { api "/api/v1/transactions/$1"; }
last_txn() { api "/api/v1/transactions?partner=$1&limit=1" | jq -r '.[0].txn_id'; }

send_rest() {  # partner file -> prints txn_id
  local p=$1 f=$2 key
  key=$(jq -r --arg p "$p" '.partners[] | select(.id==$p) | .api_key' deploy/partners.json)
  curl -s -X POST "$API/api/v1/transactions" -H "X-Partner-ID: $p" -H "X-API-Key: $key" \
       -H "X-Filename: $(basename "$f")" --data-binary @"$f" | jq -r '.txn_id'
}

CHECK_OK=1   # set to 0 by any failed check; an incident is only resolved when every check of its drill passed
expect_code() {  # txn expected_code
  local got; got=$(txn "$1" | jq -r '.failure_code // "none"')
  if [[ "$got" == "$2" ]]; then ok "$1 failed with $got (expected)"; else bad "$1 has $got, expected $2"; CHECK_OK=0; fi
}

expect_status() {  # txn expected_status
  local got; got=$(txn "$1" | jq -r '.status')
  if [[ "$got" == "$2" ]]; then ok "$1 is $got"; else bad "$1 is $got, expected $2"; CHECK_OK=0; fi
}

diagnose() { scripts/analyze_transaction.sh "$1" | sed -n '1,16p'; }

APPROVER=""
resolve_incident() {  # incident_key resolution_text  -> prints nothing, records in globals
  local key=$1 res=$2 d ans
  LAST_JIRA="-"
  [[ -z "$key" || "$key" == "null" ]] && { warn "no incident to resolve"; LAST_RESOLVED="no (no incident)"; return; }
  if [[ $CHECK_OK -eq 0 ]]; then
    bad "A check above failed, so $key stays OPEN. Fix the problem, then resolve it in the console."
    LAST_RESOLVED="NO (check failed)"; CHECK_OK=1
    LAST_JIRA=$(api "/api/v1/incidents/$key" | jq -r '.jira_key // "-"'); return
  fi
  say "AI triage draft for $key (nothing is sent yet)"
  d=$(post "/api/v1/incidents/$key/triage")
  echo "$d" | jq -r '.ai_draft | "Generated by: \(.generated_by)\nSummary: \(.summary)\nLikely root cause: \(.likely_root_cause)\n\nCustomer reply:\n\(.customer_reply)"'
  echo
  read -r -p "${B}Approve and send this reply as $APPROVER? [y/N] ${N}" ans
  if [[ "$ans" =~ ^[Yy]$ ]]; then
    post "/api/v1/incidents/$key/approve" "{\"approver\":\"$APPROVER\"}" >/dev/null
    post "/api/v1/incidents/$key/send-reply" | jq -r '"Reply sent: \(.file)"'
    post "/api/v1/incidents/$key/resolve" "{\"resolution\":\"$res\",\"by\":\"$APPROVER\"}" | jq -r '"\(.key) -> \(.status)"'
    LAST_RESOLVED="yes"
  else
    warn "Not approved: $key stays OPEN. Edit the reply in the console and approve it there if you want."
    LAST_RESOLVED="no (reply not approved)"
  fi
  LAST_JIRA=$(api "/api/v1/incidents/$key" | jq -r '.jira_key // "-"')
}

record() {  # n code failing_txn fix_txn incident
  echo "| $1 | $2 | $3 | $4 | $5 | ${LAST_JIRA:--} | ${LAST_RESOLVED:-?} |" >> "$EVID"
}

payload_case() {  # n partner badfile goodfile expected_code
  local n=$1 p=$2 badf=$3 goodf=$4 code=$5 t g inc
  CHECK_OK=1; say "Failure $n/15: $code  ($p sends $(basename "$badf"))"
  t=$(send_rest "$p" "$badf"); expect_code "$t" "$code"
  diagnose "$t"
  echo; echo "${B}Payload Doctor on the bad file:${N}"; pdoc check -b "$badf" | sed -n '1,8p'
  echo; echo "${B}Replay attempt (should be refused: the data is wrong, the partner must resend):${N}"
  post "/api/v1/transactions/$t/replay" "{\"approved_by\":\"$APPROVER\",\"reason\":\"test whether replay helps\"}" | jq -r '.detail'
  echo; echo "${B}Fix (RB-04): partner sends the corrected file $(basename "$goodf")${N}"
  g=$(send_rest "$p" "$goodf"); expect_status "$g" PROCESSED
  inc=$(txn "$t" | jq -r .incident)
  resolve_incident "$inc" "Partner resent corrected file as $g; $code fixed"
  record "$n" "$code" "$t" "$g" "$inc"
  pause
}

# ---------------------------------------------------------------- preflight
say "Preflight"
curl -fs "$API/api/v1/health" >/dev/null && ok "IntegrX API is up" || { bad "IntegrX API is not reachable. Run: docker compose up -d"; exit 1; }
for svc in api watcher order-service sftp postgres; do
  docker compose ps --status running --services | grep -qx "$svc" && ok "$svc running" || warn "$svc not running"
done
if grep -q '^JIRA_BASE_URL=https' .env 2>/dev/null; then ok "Jira configured: incidents will become Jira tickets"
else warn "Jira not configured: incidents become local tickets in data/tickets/ (resume must then say 'Jira Cloud ticket integration')"; fi
while [[ ${#APPROVER} -lt 2 ]]; do read -r -p "${B}Your name as approver (e.g. Hrushika): ${N}" APPROVER; done

open=$(api "/api/v1/incidents?status=OPEN" | jq -r '.[].key')
if [[ -n "$open" ]]; then
  echo "Open incidents from earlier test traffic: $(echo "$open" | tr '\n' ' ')"
  read -r -p "${B}Close them first so each drill gets its own incident? [Y/n] ${N}" ans
  if [[ ! "$ans" =~ ^[Nn]$ ]]; then
    for k in $open; do post "/api/v1/incidents/$k/resolve" "{\"resolution\":\"Synthetic load-test traffic; closed before failure drills\",\"by\":\"$APPROVER\"}" >/dev/null; done
    ok "closed $(echo "$open" | wc -w) incident(s)"
  fi
fi
for f in downstream-ok ack-ok mdn-ok; do scripts/inject_fault.sh "$f" >/dev/null 2>&1; done

{
  echo "# Failure drill evidence ($(date -u +%F' '%H:%M) UTC, approver $APPROVER)"
  echo
  echo "| # | Failure code | Failing TXN | Fix / replay TXN | Incident | Jira | Resolved |"
  echo "| --- | --- | --- | --- | --- | --- | --- |"
} > "$EVID"

# ---------------------------------------------------------------- 1-10 payload failures
payload_case 1  ACME01   "$PD/bad/epcis_malformed.xml"             "$PD/good/epcis_shipment.xml" INVALID_XML
payload_case 2  ACME01   "$PD/bad/epcis_duplicate_serial.xml"      "$PD/good/epcis_shipment.xml" DUPLICATE_SERIAL
payload_case 3  ACME01   "$PD/bad/epcis_aggregation_mismatch.xml"  "$PD/good/epcis_shipment.xml" AGGREGATION_MISMATCH
payload_case 4  ACME01   "$PD/bad/epcis_missing_lot_expiry.xml"    "$PD/good/epcis_shipment.xml" EPCIS_DATA_ERROR
payload_case 5  ACME01   "$PD/bad/epcis_no_owner.xml"              "$PD/good/epcis_shipment.xml" EPCIS_DATA_ERROR
payload_case 6  MEDILINE "$PD/bad/850_missing_shipto.edi"          "$PD/good/po_850.edi"         EDI_MAPPING_ERROR
payload_case 7  MEDILINE "$PD/bad/850_bad_counts.edi"              "$PD/good/po_850.edi"         EDI_ENVELOPE_ERROR
payload_case 8  MEDILINE "$PD/bad/850_truncated.edi"               "$PD/good/po_850.edi"         EDI_ENVELOPE_ERROR
payload_case 9  RETAILCO "$PD/bad/orders_no_delivery.edifact"      "$PD/good/orders.edifact"     EDI_ENVELOPE_ERROR
payload_case 10 RETAILCO "$PD/bad/inventory_bad.csv"               "$PD/good/inventory.csv"      CSV_DATA_ERROR

# ---------------------------------------------------------------- 11 AS2 certificate expired
CHECK_OK=1; say "Failure 11/15: AS2_CERT_INVALID (ACME01's AS2 certificate expires)"
scripts/inject_fault.sh as2-cert-expired ACME01 | head -1
python partner_sim/partners.py as2 ACME01 "$PD/good/asn_856.edi" | jq -r '.message'
t=$(last_txn ACME01); expect_code "$t" AS2_CERT_INVALID
diagnose "$t"
echo; echo "${B}Confirm with Payload Doctor:${N}"; pdoc as2 -b deploy/certs/acme01_cert.pem | sed -n '1,4p'
echo; echo "${B}Replay attempt (refused on purpose: the signature could not be verified):${N}"
post "/api/v1/transactions/$t/replay" "{\"approved_by\":\"$APPROVER\",\"reason\":\"test whether replay helps\"}" | jq -r '.detail'
echo; echo "${B}Fix (RB-01): renew and exchange the certificate, partner resends${N}"
python scripts/setup_certs.py --renew ACME01
python partner_sim/partners.py as2 ACME01 "$PD/good/asn_856.edi" | jq -r '.message'
g=$(last_txn ACME01); expect_status "$g" PROCESSED
inc=$(txn "$t" | jq -r .incident)
resolve_incident "$inc" "Renewed ACME01 AS2 certificate; partner resent as $g; MDN processed"
record 11 AS2_CERT_INVALID "$t" "$g" "$inc"; pause

# ---------------------------------------------------------------- 12 async MDN not delivered
CHECK_OK=1; say "Failure 12/15: AS2_MDN_NOT_DELIVERED (our receipts cannot reach the partner)"
scripts/inject_fault.sh mdn-down | tail -1
python partner_sim/partners.py as2 ACME01 "$PD/good/po_850.edi" --async-mdn http://localhost:9/mdn | jq -r '.message'
t=$(last_txn ACME01); expect_status "$t" PROCESSED
inc=$(txn "$t" | jq -r .incident)
[[ "$(api "/api/v1/incidents/$inc" | jq -r .failure_code)" == "AS2_MDN_NOT_DELIVERED" ]] && ok "incident $inc is AS2_MDN_NOT_DELIVERED (document processed, receipt not delivered)" || { bad "expected an AS2_MDN_NOT_DELIVERED incident"; CHECK_OK=0; }
diagnose "$t"
echo; echo "${B}Fix (RB-02): restore MDN delivery; partner switches to synchronous MDNs. No resend: the document was processed.${N}"
scripts/inject_fault.sh mdn-ok >/dev/null
python partner_sim/partners.py as2 ACME01 "$PD/good/asn_856.edi" | jq -r '.message'
g=$(last_txn ACME01); expect_status "$g" PROCESSED
resolve_incident "$inc" "MDN delivery restored; partner moved to synchronous MDNs (verified with $g); told partner not to resend $t"
record 12 AS2_MDN_NOT_DELIVERED "$t" "$g" "$inc"; pause

# ---------------------------------------------------------------- 13 SFTP login failure
CHECK_OK=1; say "Failure 13/15: SFTP_AUTH_FAILURE (RETAILCO cannot log in)"
scripts/inject_fault.sh sftp-wrong-password RETAILCO 2>&1 | grep -E "refused|logged" | tail -2
echo; echo "${B}Server-side evidence (RB-03):${N}"
docker compose logs --since 5m sftp 2>/dev/null | grep -iE "failed|invalid|retailco" | tail -3
r=$(post "/api/v1/incidents" "{\"failure_code\":\"SFTP_AUTH_FAILURE\",\"partner_id\":\"RETAILCO\",\"detail\":\"Partner reports SFTP login refused (3 attempts in partner-sim log)\",\"reported_by\":\"$APPROVER\"}")
inc=$(echo "$r" | jq -r .key); t=$(echo "$r" | jq -r '.transactions[0]')
[[ "$inc" != "null" ]] && ok "opened $inc ($t)" || { bad "could not open the incident: $r"; CHECK_OK=0; }
echo; echo "${B}Fix: partner uses the correct credentials and uploads again${N}"
python partner_sim/partners.py sftp RETAILCO "$PD/good/inventory.csv" | jq -r '.message'
echo "waiting for the SFTP watcher (two polls)..."; sleep 14
g=$(last_txn RETAILCO)
if [[ "$(txn "$g" | jq -r .channel)" == "SFTP" ]]; then expect_status "$g" PROCESSED
else bad "no new SFTP transaction yet; check: docker compose logs sftp watcher"; CHECK_OK=0; fi
resolve_incident "$inc" "Credentials corrected; RETAILCO uploaded over SFTP as $g"
record 13 SFTP_AUTH_FAILURE "$t" "$g" "$inc"; pause

# ---------------------------------------------------------------- 14 downstream timeout
CHECK_OK=1; say "Failure 14/15: DOWNSTREAM_TIMEOUT (order-service hangs; ~35 s: 3 attempts)"
scripts/inject_fault.sh downstream-timeout | tail -1
t=$(send_rest ACME01 "$PD/good/po_850.edi"); expect_code "$t" DOWNSTREAM_TIMEOUT
diagnose "$t"
echo; echo "${B}Health check while broken (should exit 1):${N}"; scripts/health_check.sh | grep -E "ALERT" | head -3; echo "exit=${PIPESTATUS[0]}"
echo; echo "${B}Fix (RB-05): restore order-service, then replay with an approver${N}"
scripts/inject_fault.sh downstream-ok >/dev/null
g=$(post "/api/v1/transactions/$t/replay" "{\"approved_by\":\"$APPROVER\",\"reason\":\"order-service restored\"}" | jq -r '.txn_id')
expect_status "$g" PROCESSED; expect_status "$t" REPLAYED
inc=$(txn "$t" | jq -r .incident)
resolve_incident "$inc" "order-service restored; $t replayed as $g (PROCESSED)"
record 14 DOWNSTREAM_TIMEOUT "$t" "$g" "$inc"; pause

# ---------------------------------------------------------------- 15 acknowledgement not sent
CHECK_OK=1; say "Failure 15/15: ACK_NOT_SENT (997 cannot be written)"
scripts/inject_fault.sh ack-failure | tail -1
t=$(send_rest ACME01 "$PD/good/asn_856.edi"); expect_status "$t" PROCESSED
inc=$(txn "$t" | jq -r .incident)
[[ "$(api "/api/v1/incidents/$inc" | jq -r .failure_code)" == "ACK_NOT_SENT" ]] && ok "incident $inc is ACK_NOT_SENT" || { bad "expected an ACK_NOT_SENT incident"; CHECK_OK=0; }
diagnose "$t"
echo; echo "${B}Fix (RB-02): restore the outbox, regenerate the 997 without reprocessing${N}"
scripts/inject_fault.sh ack-ok >/dev/null
ack=$(post "/api/v1/transactions/$t/resend-ack"); echo "$ack" | jq -r '"\(.result): \(.message)"'
[[ "$(echo "$ack" | jq -r .result)" == "ack_sent" ]] && ok "997 regenerated" || { bad "ack not regenerated"; CHECK_OK=0; }
resolve_incident "$inc" "Outbox restored; 997 regenerated for $t via resend-ack"
record 15 ACK_NOT_SENT "$t" "$t (ack resent)" "$inc"

# ---------------------------------------------------------------- Phase 7
say "Bash diagnostics"
echo "${B}find_errors.sh --summary${N}"; scripts/find_errors.sh "$(date -u +%F)" logs --summary | head -45
echo; echo "${B}health_check.sh (services and certificates OK; an ALERT for 'failed transactions last hour' is expected right after the drills)${N}"
scripts/health_check.sh; echo "exit=$?"
echo; echo "${B}API-down fallback: analyze_transaction.sh reads the logs with pdoc trace${N}"
first=$(sed -n '5p' "$EVID" | awk -F'|' '{gsub(/ /,"",$4); print $4}')
docker compose stop api >/dev/null 2>&1
scripts/analyze_transaction.sh "$first" 2>&1 | sed -n '1,12p'
docker compose start api >/dev/null 2>&1; sleep 5
curl -fs "$API/api/v1/health" >/dev/null && ok "API back up"

say "Done"
echo "Evidence table: $(pwd)/$EVID"
cat "$EVID"
echo
echo "Next: docker compose logs elastalert | grep -i alert   and the final Kibana screenshot."
